local connection, skipConnection, destroyConnection
local finishing=false
local function cleanup(completed)
    if not alive then return end
    alive=false
    if connection then connection:Disconnect() end
    if skipConnection then skipConnection:Disconnect() end
    if destroyConnection then destroyConnection:Disconnect() end
    restoreBackpack()
    if overlayDestroy then overlayDestroy:Disconnect() end
    gui:Destroy()
    if completed then task.spawn(function()
        local ok, err=pcall(CONFIG.OnComplete)
        if not ok then warn("Arasaka OnComplete: "..tostring(err)) end
    end) end
end
skipConnection=skip.Activated:Connect(function() cleanup(true) end)
destroyConnection=gui.Destroying:Connect(function() cleanup(false) end)
local function finish()
    if not alive or finishing then return end
    finishing=true
    if connection then connection:Disconnect() end
    -- Fade direto em cada elemento: nao rasteriza a interface inteira.
    local info=TweenInfo.new(.8,Enum.EasingStyle.Quad,Enum.EasingDirection.Out)
    for _,item in ipairs(gui:GetDescendants()) do
        local goal={}
        if item:IsA("GuiObject") then goal.BackgroundTransparency=1 end
        if item:IsA("TextLabel") or item:IsA("TextButton") then goal.TextTransparency=1; goal.TextStrokeTransparency=1 end
        if item:IsA("ViewportFrame") then goal.ImageTransparency=1 end
        if item:IsA("UIStroke") then goal.Transparency=1 end
        if next(goal) then TweenService:Create(item,info,goal):Play() end
    end
    task.delay(.85,function() cleanup(true) end)
end
local start=os.clock()
local function clamp(n) return math.clamp(n,0,1) end
local function animateFrame()
    if not alive then return end
    local t=os.clock()-start
    local p=clamp(t/CONFIG.Duration)
    local s=p*16
    local size=root.AbsoluteSize
    scale.Scale=math.max(.25,math.min(size.X/880,size.Y/720))
    local transition=clamp((s-3.4)/1.1)
    center.Visible=true
    status.TextSize=math.clamp(size.Y*.013,10,30)
    halo.BackgroundTransparency=clamp(.96-.025*math.sin(t*3)+transition*.04)
    for i,ring in ipairs(rings) do
        local diameter=ring[3]*(1+.025*math.sin(t*4+i)+transition*1.7)
        ring[1].Size=UDim2.fromOffset(diameter,diameter)
        ring[2].Transparency=clamp((i==2 and .05 or .65)+transition)
    end
    for index,part in ipairs(particles) do
        local a=part.angle+t*part.speed*(1-transition*.65)
        local burst=math.sin(clamp((s-3.3)/2)*math.pi)*170
        local r=part.radius+math.sin(t*3+part.seed)*18+burst
        local x,y=math.cos(a)*r,math.sin(a)*r*.84
        -- Deixa a area central livre para manter o rosto legivel.
        if s>5 then
            x=math.cos(a)*(r+65)
            y=math.sin(a)*(r+65)*.84
        end
        part.dot.Position=UDim2.new(.5,x,.5,y)
        part.dot.Rotation=math.deg(a)+t*70
        part.dot.BackgroundTransparency=clamp(.08+.48*(1+math.sin(t*5+part.seed))/2)
        if index<=#trails then
            local trail=trails[index]
            trail.Position=part.dot.Position
            trail.Size=UDim2.fromOffset(10+part.size*3+burst*.12,math.max(1,part.size*.23))
            trail.Rotation=math.deg(a)+90
            trail.BackgroundTransparency=.5+part.dot.BackgroundTransparency*.4
        end
    end
    for i,wave in ipairs(waves) do
        local phase=(t*.36+i/4)%1
        local diameter=220+phase*780
        wave[1].Size=UDim2.fromOffset(diameter,diameter)
        wave[2].Transparency=clamp(.45+phase*.55)
    end
    for i,line in ipairs(arcs) do
        local group=math.floor((i-1)/24)
        local segment=(i-1)%24
        local base=t*(group%2==0 and .5 or -.4)+group*2.1
        local a=base+segment*.045
        local b=a+.045
        local radius=127+group*13+math.sin(t*18+segment*2.7+group)*5
        local nextRadius=127+group*13+math.sin(t*18+(segment+1)*2.7+group)*5
        local x1,y1=math.cos(a)*radius,math.sin(a)*radius
        local x2,y2=math.cos(b)*nextRadius,math.sin(b)*nextRadius
        line.Position=UDim2.new(.5,(x1+x2)/2,.5,(y1+y2)/2)
        line.Size=UDim2.fromOffset(math.sqrt((x2-x1)^2+(y2-y1)^2)+1,1.5)
        line.Rotation=math.deg(math.atan2(y2-y1,x2-x1))
        line.BackgroundTransparency=clamp(.1+transition)
    end
    local show=clamp((s-4.1)/1.1)
    viewport.ImageTransparency=1-show
    tv.Visible=s>3.3
    diagnostic.Visible=s>3.3
    chipViewport.Visible=s>3.3
    local tvReveal=clamp((s-3.3)/.55)
    tv.Size=UDim2.fromScale(.84,.68*math.max(.008,tvReveal))
    local sentence=""
    local talking=false
    for _,entry in ipairs(dialogue) do
        if s>=entry[1] and s<entry[2] then
            local count=math.floor((s-entry[1])*CONFIG.Duration/16*32)
            sentence=string.sub(entry[3],1,count)

local function normalizedLanguage(value)
    local base = tostring(value or "en"):lower():match("^[a-z]+") or "en"
    for _, lang in ipairs(LANGUAGE_ORDER) do
        if lang == base then return base end
    end
    return "en" -- Unsupported Roblox locales receive English interface where translated.
end
local okLocale, robloxLocale = pcall(function()
    return LocalizationService.RobloxLocaleId
end)
ArasakaI18n.Language = normalizedLanguage(okLocale and robloxLocale or "pt")

-- Case-insensitive matching includes common Portuguese accented capitals.
local FOLD_ACCENTS = {
    ["Á"]="á", ["À"]="à", ["Â"]="â", ["Ã"]="ã",
    ["É"]="é", ["Ê"]="ê", ["Í"]="í", ["Ó"]="ó",
    ["Ô"]="ô", ["Õ"]="õ", ["Ú"]="ú", ["Ç"]="ç",
}
local function foldText(s)
    s = s:lower()
    for upper, lower in pairs(FOLD_ACCENTS) do
        s = s:gsub(upper, lower)
    end
    return s
end
for _, dict in pairs(TRANSLATIONS) do
    for _, pair in ipairs(dict) do
        pair[3] = foldText(pair[1])
    end
end
local function translateText(original, language)
    if language == "pt" or type(original) ~= "string" or #original == 0 then
        return original
    end
    -- Protect user content and rich-text markup; never translate editable TextBoxes.
    if #original > 350 or original:find("<font", 1, true) or original:find("</", 1, true) then
        return original
    end
    local result = original
    local folded = foldText(result)
    local dict = TRANSLATIONS[language]
    if not dict then return original end
    -- Longest phrases first; only replace whole tokens, not portions of game IDs.
    for _, pair in ipairs(dict) do
        local source, translated, foldedSource = pair[1], pair[2], pair[3]
        local startFrom = 1
        while startFrom <= #result do
            local a, b = folded:find(foldedSource, startFrom, true)
            if not a then break end
            local left = a == 1 and "" or result:sub(a-1, a-1)
            local right = b == #result and "" or result:sub(b+1, b+1)
            local srcFirst, srcLast = source:sub(1, 1), source:sub(-1)
            local leftOK = not srcFirst:match("[%w]") or not left:match("[%w]")
            local rightOK = not srcLast:match("[%w]") or not right:match("[%w]")
            if leftOK and rightOK then
                result = result:sub(1, a-1) .. translated .. result:sub(b+1)
                folded = foldText(result)
                startFrom = a + #translated
            else
                startFrom = b + 1
            end
        end
    end
    return result
end

function ArasakaI18n:UpdateObject(obj, property)
    if not self.Active or not obj or not obj.Parent then return end
    if obj.Name == "ArasakaLanguageButton" then return end
    local origin = self.Sources[obj]
    if type(origin) ~= "string" then return end
    local rendered = translateText(origin, self.Language)
    -- Remember the output before writing: Roblox signals can be deferred.
    self.Rendered[obj] = rendered
    if obj[property] ~= rendered then
        obj[property] = rendered
    end
end

function ArasakaI18n:Owned(obj)
    local cur = obj
    while cur and cur ~= self.PlayerGui do
        if cur:IsA("ScreenGui") and cur.Name:sub(1, 7) == "Arasaka" then
            return true
        end
        cur = cur.Parent
    end
    return false
end

function ArasakaI18n:Bind(obj)
    if not self:Owned(obj) or self.Connections[obj] then return end
    local property
    if obj:IsA("TextLabel") or obj:IsA("TextButton") then
        property = "Text"
    elseif obj:IsA("TextBox") then
        property = "PlaceholderText" -- never translate user-entered data or key input
    else
        return
    end
    if obj.Name == "ArasakaLanguageButton" then return end
    self.Sources[obj] = obj[property]
    self.Connections[obj] = obj:GetPropertyChangedSignal(property):Connect(function()
        if not self.Active or obj[property] == self.Rendered[obj] then return end
        self.Sources[obj] = obj[property]
        self:UpdateObject(obj, property)
    end)
    self:UpdateObject(obj, property)
end

function ArasakaI18n:Unbind(obj)
    local conn = self.Connections[obj]
    if conn then
        conn:Disconnect()
        self.Connections[obj] = nil
    end
    self.Sources[obj] = nil
    self.Rendered[obj] = nil
end

function ArasakaI18n:SetLanguage(lang)
    self.Language = normalizedLanguage(lang)
    for obj in pairs(self.Connections) do
        if obj and obj.Parent then
            local property = obj:IsA("TextBox") and "PlaceholderText" or "Text"
            self:UpdateObject(obj, property)
        end
    end
end

function ArasakaI18n:NextLanguage()
    for idx, name in ipairs(LANGUAGE_ORDER) do
        if name == self.Language then
            local nextIdx = idx % #LANGUAGE_ORDER + 1
            self:SetLanguage(LANGUAGE_ORDER[nextIdx])
            return self.Language
        end
    end
    self:SetLanguage("pt")
    return self.Language
end

function ArasakaI18n:Start(playerGui)
    if self.Active then return end
    self.Active, self.PlayerGui = true, playerGui
    self.RootAdded = playerGui.DescendantAdded:Connect(function(obj)
        if self.Active then self:Bind(obj) end
    end)
    self.RootRemoving = playerGui.DescendantRemoving:Connect(function(obj)
        -- Release all descendants if an entire Arasaka overlay is destroyed.
        if obj:IsA("ScreenGui") then
            for _, child in ipairs(obj:GetDescendants()) do self:Unbind(child) end
        end
        self:Unbind(obj)
    end)
    -- Scan only owned overlays, not the whole game's interface tree.
    for _, root in ipairs(playerGui:GetChildren()) do
        if root:IsA("ScreenGui") and root.Name:sub(1, 7) == "Arasaka" then
            for _, obj in ipairs(root:GetDescendants()) do self:Bind(obj) end
        end
    end
end
function ArasakaI18n:Stop()
    self.Active = false
    if self.RootAdded then self.RootAdded:Disconnect(); self.RootAdded = nil end
    if self.RootRemoving then self.RootRemoving:Disconnect(); self.RootRemoving = nil end
    for obj in pairs(self.Connections) do self:Unbind(obj) end
    self.PlayerGui = nil
end
